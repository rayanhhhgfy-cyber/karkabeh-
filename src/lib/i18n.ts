export function t(locale: Locale, key: string, values?: Record<string, string>) {
  const text = translations[locale]?.[key] ?? translations.en[key] ?? key;
  if (!values) return text;
  return Object.entries(values).reduce(
    (acc, [name, value]) => acc.replace(new RegExp(`\\{\\{${name}\\}\\}`, "g"), value),
    text,
  );
}

